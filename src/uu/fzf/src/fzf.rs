// RecurBusyBox - a multi-call binary of high-performance Rust tools.
//
// `fzf`: a NON-INTERACTIVE fuzzy filter. The interactive TUI of the original
// `fzf` is explicitly out of scope (this runs inside agent shells with no
// terminal UI); instead it reads candidate lines and prints the best matches
// for a pattern, ordered best-first. Fuzzy scoring is delegated to
// `nucleo-matcher`, the same pure-Rust matcher the Helix editor uses.
//
// Usage: fzf [OPTIONS] <PATTERN> [FILE...]
//   - no FILE args: candidates are read from stdin (one per line)
//   - FILE args:    candidates are the lines of those files
//   - --find:       candidates are generated by walking the filesystem
//                   (honouring .gitignore via `ignore::WalkBuilder`)

use std::fs::File;
use std::io::{self, BufRead, Read as _, Write as _};
use std::path::{Path, PathBuf};

use clap::{Arg, ArgAction, Command};
use ignore::WalkBuilder;
use nucleo_matcher::{Config, Matcher, Utf32Str};

/// How to order candidates that have an equal fuzzy score.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Tiebreak {
    /// Fall back to original input order (the default).
    Score,
    /// Fall back to original input order.
    Index,
    /// Prefer the shorter candidate, then original input order.
    Length,
}

struct Options {
    pattern: String,
    files: Vec<PathBuf>,
    n: Option<usize>,
    exact: bool,
    case_sensitive: bool,
    tiebreak: Tiebreak,
    find: bool,
}

pub fn uu_app() -> Command {
    Command::new("fzf")
        .version(uucore::crate_version!())
        .about("Non-interactive fuzzy filter (fzf subset).")
        .arg(Arg::new("pattern").value_name("PATTERN"))
        .arg(Arg::new("files").value_name("FILE").num_args(0..))
        .arg(
            Arg::new("n")
                .short('n')
                .long("n")
                .value_name("K")
                .help("return at most K matches"),
        )
        .arg(
            Arg::new("exact")
                .short('e')
                .long("exact")
                .action(ArgAction::SetTrue)
                .help("exact substring match instead of fuzzy"),
        )
        .arg(
            Arg::new("ignore-case")
                .short('i')
                .long("ignore-case")
                .action(ArgAction::SetTrue)
                .help("case-insensitive matching (default on)"),
        )
        .arg(
            Arg::new("case-sensitive")
                .long("case-sensitive")
                .action(ArgAction::SetTrue)
                .help("turn case-insensitive matching off"),
        )
        .arg(
            Arg::new("tiebreak")
                .short('x')
                .long("tiebreak")
                .value_name("index|length|score")
                .help("ordering preference among equally-scoring matches"),
        )
        .arg(
            Arg::new("find")
                .long("find")
                .action(ArgAction::SetTrue)
                .help("generate candidates by walking the filesystem"),
        )
}

/// Parse the argv tail (without argv[0]) into [`Options`].
/// `Err(Some(msg))` is a usage error; `Err(None)` means the app already
/// handled the request (`--help` / `--version`).
fn parse(argv: &[String]) -> Result<Options, Option<String>> {
    let mut opts = Options {
        pattern: String::new(),
        files: Vec::new(),
        n: None,
        exact: false,
        case_sensitive: false,
        tiebreak: Tiebreak::Score,
        find: false,
    };
    let mut positionals: Vec<String> = Vec::new();
    let mut no_more_flags = false;
    let mut iter = argv.iter();
    while let Some(a) = iter.next() {
        if no_more_flags {
            positionals.push(a.clone());
            continue;
        }
        // Support `--flag=value` for the long options that take a value.
        let (name, inline) = match a.split_once('=') {
            Some((n, v)) if n.starts_with("--") => (n, Some(v.to_string())),
            _ => (a.as_str(), None),
        };
        match name {
            "--" => no_more_flags = true,
            "-e" | "--exact" => opts.exact = true,
            "-i" | "--ignore-case" => {} // default is already case-insensitive
            "--case-sensitive" => opts.case_sensitive = true,
            "--find" => opts.find = true,
            "-n" | "--n" | "--number" => {
                let v = inline
                    .or_else(|| iter.next().cloned())
                    .ok_or_else(|| usage("-n needs a value"))?;
                let k = v.parse::<usize>().map_err(|_| format!("invalid -n value '{v}'"))?;
                opts.n = Some(k);
            }
            "-x" | "--tiebreak" => {
                let v = inline
                    .or_else(|| iter.next().cloned())
                    .ok_or_else(|| usage("--tiebreak needs a value"))?;
                opts.tiebreak = match v.as_str() {
                    "index" => Tiebreak::Index,
                    "length" => Tiebreak::Length,
                    "score" => Tiebreak::Score,
                    other => {
                        return Err(Some(format!(
                            "invalid tiebreak '{other}' (expected index, length or score)"
                        )))
                    }
                };
            }
            "-h" | "--help" => {
                let _ = uu_app().print_help();
                return Err(None);
            }
            "-V" | "--version" => {
                let _ = writeln!(io::stdout(), "fzf {}", uucore::crate_version!());
                return Err(None);
            }
            // Attached short values: -nK.
            s if s.starts_with("-n") && s.len() > 2 => {
                let v = &s[2..];
                let k = v
                    .parse::<usize>()
                    .map_err(|_| format!("invalid -n value '{v}'"))?;
                opts.n = Some(k);
            }
            s if s.starts_with("-x") && s.len() > 2 => {
                let v = &s[2..];
                opts.tiebreak = match v {
                    "index" => Tiebreak::Index,
                    "length" => Tiebreak::Length,
                    "score" => Tiebreak::Score,
                    other => {
                        return Err(Some(format!(
                            "invalid tiebreak '{other}' (expected index, length or score)"
                        )))
                    }
                };
            }
            s if s.starts_with('-') && s != "-" => {
                return Err(Some(s.to_string()));
            }
            _ => positionals.push(a.clone()),
        }
    }

    let mut it = positionals.into_iter();
    opts.pattern = it
        .next()
        .ok_or_else(|| usage("a pattern is required"))?;
    opts.files = it.map(PathBuf::from).collect();
    Ok(opts)
}

fn usage(what: &str) -> String {
    format!("{what} (usage: fzf [OPTIONS] <PATTERN> [FILE...])")
}

/// Collect the candidate lines according to the input mode.
fn collect_candidates(opts: &Options) -> Result<Vec<String>, String> {
    let mut candidates: Vec<String> = Vec::new();

    if opts.find {
        // Generate candidates by walking the filesystem. Start at `.` when no
        // explicit paths were given.
        let roots: Vec<PathBuf> = if opts.files.is_empty() {
            vec![PathBuf::from(".")]
        } else {
            opts.files.clone()
        };
        for root in &roots {
            let start = if root.as_os_str().is_empty() {
                Path::new(".")
            } else {
                root.as_path()
            };
            let mut builder = WalkBuilder::new(start);
            builder.hidden(false);
            builder.git_ignore(true);
            for entry in builder.build() {
                let Ok(entry) = entry else {
                    continue;
                };
                // Never emit the walk root directory itself.
                if entry.depth() == 0 && entry.file_type().is_some_and(|t| t.is_dir()) {
                    continue;
                }
                let text = entry.path().to_string_lossy().into_owned();
                if !text.is_empty() {
                    candidates.push(text);
                }
            }
        }
        return Ok(candidates);
    }

    if opts.files.is_empty() {
        // Read candidates from stdin, one line each.
        let stdin = io::stdin();
        let mut lock = stdin.lock();
        let mut line = String::new();
        loop {
            line.clear();
            match lock.read_line(&mut line) {
                Ok(0) => break,
                Ok(_) => {
                    strip_newline(&mut line);
                    candidates.push(line.clone());
                }
                Err(e) => return Err(format!("failed to read stdin: {e}")),
            }
        }
        return Ok(candidates);
    }

    // Read candidate lines from the given files.
    for path in &opts.files {
        if path.is_dir() {
            return Err(format!("{} is a directory (did you mean --find?)", path.display()));
        }
        let file = File::open(path)
            .map_err(|e| format!("failed to open {}: {e}", path.display()))?;
        let mut reader = io::BufReader::new(file);
        let mut buf = Vec::new();
        reader
            .read_to_end(&mut buf)
            .map_err(|e| format!("failed to read {}: {e}", path.display()))?;
        let text = String::from_utf8_lossy(&buf).into_owned();
        for line in text.lines() {
            candidates.push(line.to_string());
        }
    }
    Ok(candidates)
}

fn strip_newline(line: &mut String) {
    if line.ends_with('\n') {
        line.pop();
        if line.ends_with('\r') {
            line.pop();
        }
    }
}

/// A scored candidate: original input order index, fuzzy score, and line.
struct Matched {
    index: usize,
    score: u32,
    line: String,
}

fn run(opts: &Options) -> Result<u32, String> {
    let candidates = collect_candidates(opts)?;

    let mut config = Config::DEFAULT;
    // `--ignore-case` is the default; `--case-sensitive` turns folding off.
    config.ignore_case = !opts.case_sensitive;
    let mut matcher = Matcher::new(config);

    // Build the needle once. For case-insensitive fuzzy/substring matching we
    // lower-case the needle ourselves (mirroring nucleo's own tests) so the
    // matcher only has to fold the haystack.
    let needle_str = if opts.case_sensitive || opts.exact {
        opts.pattern.clone()
    } else {
        opts.pattern.to_lowercase()
    };
    let mut needle_buf: Vec<char> = Vec::new();
    let needle = Utf32Str::new(&needle_str, &mut needle_buf);

    let mut matched: Vec<Matched> = Vec::new();
    for (index, line) in candidates.into_iter().enumerate() {
        let score = if opts.exact {
            // Exact substring match. Fold the haystack (not the pattern) when
            // case-insensitive, matching against the pattern verbatim.
            let folded = if opts.case_sensitive {
                line.clone()
            } else {
                line.to_lowercase()
            };
            let mut fb: Vec<char> = Vec::new();
            let hs = Utf32Str::new(&folded, &mut fb);
            let mut nb: Vec<char> = Vec::new();
            let nd = Utf32Str::new(&opts.pattern, &mut nb);
            matcher.substring_match(hs, nd)
        } else {
            let mut hb: Vec<char> = Vec::new();
            let haystack = Utf32Str::new(&line, &mut hb);
            matcher.fuzzy_match(haystack, needle)
        };
        if let Some(s) = score {
            matched.push(Matched {
                index,
                score: u32::from(s),
                line,
            });
        }
    }

    // Order best-first: highest score, then the tiebreak rule.
    matched.sort_by(|a, b| match b.score.cmp(&a.score) {
        std::cmp::Ordering::Equal => match opts.tiebreak {
            Tiebreak::Length => b
                .line
                .chars()
                .count()
                .cmp(&a.line.chars().count())
                .reverse()
                .then(a.index.cmp(&b.index)),
            Tiebreak::Index | Tiebreak::Score => a.index.cmp(&b.index),
        },
        other => other,
    });

    if let Some(k) = opts.n {
        matched.truncate(k);
    }

    let out = io::stdout();
    let mut out = out.lock();
    let matched_any = !matched.is_empty();
    for m in &matched {
        let _ = writeln!(out, "{}", m.line);
    }
    out.flush().map_err(|e| e.to_string())?;

    Ok(u32::from(!matched_any))
}

pub fn uumain(args: impl uucore::Args) -> i32 {
    let argv: Vec<String> = args.map(|a| a.to_string_lossy().into_owned()).collect();
    let tail = if argv.is_empty() { &argv[..] } else { &argv[1..] };
    match parse(tail) {
        Ok(opts) => match run(&opts) {
            Ok(code) => code as i32,
            Err(e) => {
                let _ = writeln!(io::stderr(), "fzf: {e}");
                2
            }
        },
        Err(Some(msg)) => {
            let _ = writeln!(io::stderr(), "fzf: {msg}");
            2
        }
        Err(None) => 0,
    }
}
